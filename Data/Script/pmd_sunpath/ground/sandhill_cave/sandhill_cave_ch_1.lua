require 'pmd_sunpath.common'
require 'pmd_sunpath.PartnerEssentials'
require 'pmd_sunpath.CharacterEssentials'
require 'pmd_sunpath.CharacterActions'

sandhill_cave_ch_1 = {}

-------------------------------
--Cutscene functions
-------------------------------
--The cutscene for the Sandhill Cave dungeon before the team enters it.
function sandhill_cave_ch_1.Story_Cutscene()
	local hero = CH('PLAYER')
	local partner = CH('Teammate1')
	UI:ResetSpeaker()
	GROUND:TeleportTo(hero, 291, 361, Direction.Up)
	GROUND:TeleportTo(partner, 261, 361, Direction.Up)
	AI:DisableCharacterAI(partner)

	GAME:CutsceneMode(true)
	UI:ResetSpeaker()
	UI:WaitShowTitle(GAME:GetCurrentGround().Name:ToLocal(), 20)
	GAME:WaitFrames(60)
	UI:WaitHideTitle(20)
	GAME:FadeIn(40)
	UI:ResetSpeaker()
	GAME:WaitFrames(20)
	local coro1 = TASK:BranchCoroutine(function () GROUND:MoveToPosition(hero, 291, 321, false, 1) end)
	local coro2 = TASK:BranchCoroutine(function () GAME:WaitFrames(10)
												   GROUND:MoveToPosition(partner, 261, 321, false, 1)
												   GAME:WaitFrames(10) end)
	TASK:JoinCoroutines({coro1, coro2})
	GAME:WaitFrames(20)
	coro1 = TASK:BranchCoroutine(function () CharacterActions.LookAround(hero, 3, 4, false, false, true, Direction.Up) end)
	coro2 = TASK:BranchCoroutine(function () GAME:WaitFrames(10)
											 CharacterActions.LookAround(partner, 3, 4, false, false, true, Direction.Up)
											 GAME:WaitFrames(5) end)
	TASK:JoinCoroutines({coro1, coro2})
	GAME:WaitFrames(20)
	coro1 = TASK:BranchCoroutine(function () GROUND:CharAnimateTurnTo(hero, Direction.Left, 4) end)
	coro2 = TASK:BranchCoroutine(function () GAME:WaitFrames(10)
											 GROUND:CharAnimateTurnTo(partner, Direction.Right, 4)
											 GAME:WaitFrames(5) end)
	TASK:JoinCoroutines({coro1, coro2})
	GAME:WaitFrames(20)
	UI:SetSpeaker(partner, true)
	UI:SetSpeakerEmotion('Normal')
	UI:WaitShowDialogue("Hey, " .. hero:GetDisplayName() .. ", we made it to the end!")
	GAME:WaitFrames(20)
	coro1 = TASK:BranchCoroutine(function () GROUND:CharAnimateTurnTo(hero, Direction.Left, 4) end)
	coro2 = TASK:BranchCoroutine(function () GAME:WaitFrames(10)
											 GROUND:CharAnimateTurnTo(partner, Direction.Right, 4)
											 GAME:WaitFrames(5) end)
	TASK:JoinCoroutines({coro1, coro2})
	GAME:WaitFrames(10)
	UI:WaitShowDialogue("Come on, let's go.")
	GAME:WaitFrames(20)
	local coro1 = TASK:BranchCoroutine(function () GROUND:MoveToPosition(partner, 261, 165, false, 1) end)
	local coro2 = TASK:BranchCoroutine(function () GAME:WaitFrames(25)
												   GROUND:MoveToPosition(hero, 291, 165, false, 1)
												   GAME:WaitFrames(10) end)
	TASK:JoinCoroutines({coro1, coro2})
	GAME:WaitFrames(20)
	CharacterActions.LookAround(partner, 3, 4, false, false, true, Direction.Right)
	GAME:WaitFrames(30)
	GROUND:CharAnimateTurnTo(hero, Direction.Left, 4)
	GAME:WaitFrames(20)
	UI:SetSpeakerEmotion('Worried')
	UI:WaitShowDialogue(".....")
	UI:WaitShowDialogue("Hmm...there doesn't seem to much here.")
	GAME:WaitFrames(5)
	UI:SetSpeakerEmotion('Happy')
	UI:WaitShowDialogue("I don't really mind that though. It was really fun having someone to explore with!")
	GAME:WaitFrames(5)
	UI:SetSpeakerEmotion('Normal')
	UI:WaitShowDialogue("That being said, we should probably head back before we get in trouble.")
	GAME:WaitFrames(20)
	UI:SetSpeaker(hero)
	UI:SetSpeakerEmotion('Normal')
	UI:WaitShowDialogue("Yeah, we probably should.")
	GAME:WaitFrames(5)
	CharacterActions.LookAround(hero, 3, 4, false, false, true, Direction.Down)
	GAME:WaitFrames(10)
	GROUND:CharAnimateTurnTo(hero, Direction.Left, 4)
	UI:SetSpeaker(hero, false)
	UI:SetSpeakerEmotion('Worried')
	UI:WaitShowDialogue("(Why do I feel like there's more to this place than it lets on, though...?)")
	GAME:WaitFrames(20)
	UI:SetSpeaker(partner, true)
	UI:SetSpeakerEmotion('Worried')
	UI:WaitShowDialogue("Are you ok? You seem to be lost in thought.")
	GAME:WaitFrames(20)
	UI:SetSpeaker(hero)
	UI:SetSpeakerEmotion('Normal')
	UI:WaitShowDialogue("O-oh. Yeah, I'm fine.")
	GAME:WaitFrames(20)
	UI:SetSpeaker(partner)
	UI:WaitShowDialogue("If you say so. Let's go, though.")
	GAME:WaitFrames(20)
	UI:SetSpeaker(hero)
	UI:WaitShowDialogue("Alright.")
	coro1 = TASK:BranchCoroutine(function () GROUND:CharAnimateTurnTo(hero, Direction.Down, 4) end)
	coro2 = TASK:BranchCoroutine(function () GAME:WaitFrames(10)
											 GROUND:CharAnimateTurnTo(partner, Direction.Down, 4)
											 GAME:WaitFrames(5) end)
	TASK:JoinCoroutines({coro1, coro2})
	GAME:WaitFrames(20)
	local coro1 = TASK:BranchCoroutine(function () GROUND:MoveToPosition(partner, 261, 410, false, 1) end)
	local coro2 = TASK:BranchCoroutine(function () GAME:WaitFrames(25)
												   GROUND:MoveToPosition(hero, 291, 410, false, 1)
												   GAME:WaitFrames(10) end)
	TASK:JoinCoroutines({coro1, coro2})
	local cavedweller = 
		CharacterEssentials.MakeCharactersFromList({
			{"Sandslash", 485, 213, Direction.Left}
		})
	
	
	
	
	GAME:WaitFrames(120)
	GAME:MoveCamera(306, 176, 120, false)
	GAME:WaitFrames(20)
	GROUND:MoveToPosition(cavedweller, 370, 213, false, 1)
	GAME:WaitFrames(20)
	GROUND:MoveToPosition(cavedweller, 292, 155, false, 1)
	GAME:WaitFrames(20)
	GROUND:CharAnimateTurnTo(cavedweller, Direction.Down, 4)
	GAME:WaitFrames(20)
	UI:SetSpeaker(cavedweller)
	UI:SetSpeakerEmotion('Worried')
	UI:WaitShowDialogue("Were those others I saw just now?")
	GAME:WaitFrames(10)
	UI:SetSpeakerEmotion('Normal')
	UI:WaitShowDialogue("No matter, they're gone now. Less trouble for me if anything, to be honest...")
	GAME:WaitFrames(20)
	GAME:FadeOut(false, 20)
	GAME:WaitFrames(60)
	
	SV.Chapter1.TeamCompletedSandCave = true
	GAME:CutsceneMode(false)
	GAME:EnterGroundMap("qahil_village", "Entrance_Marker_2")
	
end
