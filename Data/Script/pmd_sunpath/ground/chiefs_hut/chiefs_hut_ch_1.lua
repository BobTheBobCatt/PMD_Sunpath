require 'pmd_sunpath.common'
require 'pmd_sunpath.PartnerEssentials'
require 'pmd_sunpath.CharacterEssentials'
require 'pmd_sunpath.CharacterActions'
require 'pmd_sunpath.DialogueFunctions'

chiefs_hut_ch_1 = {}

-------------------------------
--Cutscene functions
-------------------------------
--Play this cutscene after the scene where the guard leads the player to the chief's hut
function chiefs_hut_ch_1.Story_Cutscene()
	local hero = CH('PLAYER')
	local chief = CH('Krookodile')
	GROUND:Hide('Teammate1')
	local marker = MRKR("Main_Entrance_Marker")
	UI:ResetSpeaker()
	SOUND:PlayBGM('Qahil Village.ogg', true)
	GROUND:TeleportTo(hero, marker.Position.X, marker.Position.Y, Direction.Up)
	local guard = 
		CharacterEssentials.MakeCharactersFromList({
			{"Absol", 171, 148, Direction.Up}
		})
	
	
	
	GAME:CutsceneMode(true)
	GAME:FadeIn(120)
	GAME:WaitFrames(60)
	UI:SetSpeaker(guard, true)
	GROUND:MoveToPosition(hero, 171, 215, false, 1)
	GAME:WaitFrames(20)
	GROUND:CharAnimateTurnTo(guard, Direction.Down, 4)
	GAME:WaitFrames(20)
	GROUND:CharAnimateTurnTo(guard, Direction.Up, 4)
	UI:SetSpeakerEmotion('Normal')
	UI:WaitShowDialogue("Chief, an outsider has asked to stay with us for awhile. I believe you should handle the situation.")
	GAME:WaitFrames(20)
	UI:SetSpeaker(chief)
	UI:WaitShowDialogue("Is that so? Very well, then. Have them step forward.")
	GAME:WaitFrames(20)
	UI:SetSpeaker(guard)
	UI:WaitShowDialogue("Right.")
	GAME:WaitFrames(20)
	GROUND:MoveToPosition(guard, 220, 148, false, 1)
	GAME:WaitFrames(20)
	GROUND:CharAnimateTurnTo(guard, Direction.Left, 4)
	GAME:WaitFrames(20)
	GROUND:MoveToPosition(hero, 171, 148, false, 1)
	GAME:WaitFrames(20)
	UI:SetSpeaker(chief)
	UI:WaitShowDialogue("So, it's you that wish to stay in our village?")
	GAME:WaitFrames(10)
	CharacterActions.EmoteAndPause(hero, "Exclaim", true)
	UI:WaitShowDialogue("You're certainly younger than I was expecting. Not many child wanderers around these parts...")
	UI:SetSpeaker(chief, false)
	UI:SetSpeakerEmotion('Worried')
	GAME:WaitFrames(20)
	UI:WaitShowDialogue("(I sure hope " .. DialogueFunctions.GetPronoun(hero, "they", false) .. " " .. DialogueFunctions.GetPronoun(hero, "aren't", false) .. " another troublemaker. We already have one as it is...)")
	GAME:WaitFrames(20)
	UI:SetSpeaker(hero, true)
	UI:SetSpeakerEmotion('Normal')
	UI:WaitShowDialogue("Yes, I wish to stay here for awhile.")
	UI:SetSpeakerEmotion('Worried')
	UI:WaitShowDialogue("I-if that's fine with you, that is...")
	GAME:WaitFrames(20)
	UI:SetSpeaker(chief)
	UI:SetSpeakerEmotion('Joyous')
	UI:WaitShowDialogue("Hahaha! You don't have to seem so frightened or tense, you know.")
	GAME:WaitFrames(20)
	CharacterActions.EmoteAndPause(hero, "Sweatdrop", true)
	UI:SetSpeakerEmotion('Normal')
	UI:WaitShowDialogue("But yes, you can stay. However...")
	GAME:WaitFrames(20)
	UI:SetSpeaker(hero)
	UI:SetSpeakerEmotion('Stunned')
	UI:WaitShowDialogue("However?")
	GAME:WaitFrames(20)
	UI:SetSpeaker(chief)
	UI:SetSpeakerEmotion('Determined')
	UI:WaitShowDialogue("You watch yourself now. If I find out that anyone has come to harm due to you, I'll kick you right back out into the desert. Understand?")
	GAME:WaitFrames(20)
	UI:SetSpeaker(hero)
	UI:SetSpeakerEmotion('Surprised')
	UI:WaitShowDialogue("Y-yes! Understood.")
	UI:SetSpeakerEmotion('Inspired')
	UI:WaitShowDialogue("And thanks!")
	GAME:WaitFrames(20)
	UI:SetSpeaker(chief)
	UI:SetSpeakerEmotion('Normal')
	UI:WaitShowDialogue("Good, and no problem.")
	GAME:WaitFrames(20)
	GROUND:CharAnimateTurnTo(chief, Direction.DownRight, 4)
	GAME:WaitFrames(20)
	UI:WaitShowDialogue("" .. CharacterEssentials.GetCharacterName("Absol") .. ".")
	GAME:WaitFrames(20)
	GROUND:CharAnimateTurnTo(guard, Direction.UpLeft, 4)
	UI:SetSpeaker(guard)
	UI:WaitShowDialogue("Yes?")
	GAME:WaitFrames(20)
	UI:SetSpeaker(chief)
	UI:WaitShowDialogue("We still have that spare tent set up, right?")
	GAME:WaitFrames(20)
	UI:SetSpeaker(guard)
	UI:WaitShowDialogue("I believe so, yeah.")
	GAME:WaitFrames(20)
	UI:SetSpeaker(chief)
	UI:WaitShowDialogue("Show " .. DialogueFunctions.GetPronoun(hero, "them", false) .. " to " .. DialogueFunctions.GetPronoun(hero, "their", false) .. " tent. After that, you should return to watch duty.")
	GAME:WaitFrames(20)
	UI:SetSpeaker(guard)
	UI:WaitShowDialogue("Right.")
	GROUND:MoveToPosition(guard, 171, 215, false, 1)
	GAME:WaitFrames(10)
	local coro1 = TASK:BranchCoroutine(function () GAME:WaitFrames(10)
									GROUND:CharAnimateTurnTo(guard, Direction.Up, 4) end)
	local coro2 = TASK:BranchCoroutine(function () GAME:WaitFrames(20)
									GROUND:CharAnimateTurnTo(hero, Direction.Down, 4)
									GAME:WaitFrames(10) end)
	TASK:JoinCoroutines({coro1, coro2})
	GAME:WaitFrames(5)
	GROUND:CharAnimateTurnTo(chief, Direction.Down, 4)
	GAME:WaitFrames(20)
	UI:SetSpeaker(guard)
	UI:WaitShowDialogue("Alright, kid. It's time for you to follow me again, I'll show where you'll be staying.")
	GAME:WaitFrames(20)
	CharacterActions.DoAnimation(hero, "Nod")
	GAME:WaitFrames(20)
	GROUND:CharAnimateTurnTo(guard, Direction.Down, 4)
	GAME:WaitFrames(10)
	coro1 = TASK:BranchCoroutine(function () GAME:WaitFrames(10)
									GROUND:MoveToPosition(guard, 171, 310, false, 1) end)
	coro2 = TASK:BranchCoroutine(function () GAME:WaitFrames(40)
									GROUND:MoveToPosition(hero, 171, 250, false, 1)
									GAME:WaitFrames(10) end)
	TASK:JoinCoroutines({coro1, coro2})
	GAME:WaitFrames(10)
	GAME:FadeOut(false, 20)
	GAME:WaitFrames(60)
	
	SV.Chapter1.PlayerAllowedInVillage = true
	GAME:CutsceneMode(false)
	GAME:EnterGroundMap("qahil_village", "ChiefsHutEntranceMarker")	
	
end
