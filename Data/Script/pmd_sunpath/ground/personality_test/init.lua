local function addNature(question, answer)
	local questionMap = natureMap[question]
	if not questionMap then
		return
	end
	local points = questionMap[answer]
	if not points then
		return
	end
	for _, res in ipairs(points) do
		natures[res.nature] = (natures[res.nature] or 0) + res.points
	end
end

local function roll(randMin, randMax)
	local cont = 0
	local rand = 0
	while cont < 10 do
		cont = math.random(1, 10)
		rand = math.random(randMin, randMax)
	end

	return rand
end]]
