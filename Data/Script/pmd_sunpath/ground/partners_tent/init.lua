function partners_tent.StoryScripting()
  --story scripting
	if SV.ChapterProgression.Chapter == 1 then 
		if SV.Chapter1.PartnerEnteredVillage and not SV.Chapter1.PlayerSleptInVillage then
			partners_tent_ch_1.Story_Cutscene()
		elseif SV.Chapter1.PlayerSleptInVillage and not SV.Chapter1.PlayerMetPartner then
			partners_tent_ch_1.Story_Cutscene2()
		elseif SV.Chapter1.TeamCompletedSandCave then
			partners_tent_ch_1.Story_Cutscene3()
		else
			GAME:FadeIn(20)
		end
	else
		GAME:FadeIn(20)
	end
end

