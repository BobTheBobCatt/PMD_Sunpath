function dusty_dune.StoryScripting()
  --Story scripting
	if SV.ChapterProgression.Chapter == 1 then 
		if not SV.Chapter1.PlayedIntroCutscene then --Opening Cutscene on a fresh save
			dusty_dune_ch_1.Intro_Cutscene() -- The intro cutscene after the Personality "Test" is complete.
		elseif SV.Chapter1.PlayerEnteredDune and not SV.Chapter1.PlayerCompletedDune then
			dusty_dune_ch_1.WipedInDune() -- Cutscene that plays if the partner faints in the dune
		elseif SV.Chapter1.PartnerCompletedDune and not SV.Chapter1.PlayerEnteredVillage then
			dusty_dune_ch_1.Partner_Cutscene() -- Cutscene that plays if the partner completes Dusty Dune
		end
	else 
		dusty_dune.GenericEnding() -- Cutscene that plays if completing Dusty Dune and there's no other story scenes to play
	end
end

