function players_tent.StoryScripting()
  --story scripting
	if SV.ChapterProgression.Chapter == 1 then 
		if SV.Chapter1.PlayerAllowedInVillage and not SV.Chapter1.PartnerEnteredVillage then
			players_tent_ch_1.Story_Cutscene() -- Scene where the player enters their tent to find nothing in it
		elseif SV.Chapter1.PartnerEnteredVillage and not SV.Chapter1.PlayerSleptInVillage then
			players_tent_ch_1.Story_Cutscene2() -- Scene where the player makes their bed and then falls asleep afterwards
		elseif SV.Chapter1.PlayerSleptInVillage and not SV.Chapter1.PlayerMetPartner then
			players_tent_ch_1.Story_Cutscene3() -- Scene where the partner accidentally wakes up the player and ends up meeting them
		elseif SV.Chapter1.TeamCompletedSandCave then
			players_tent_ch_1.Story_Cutscene4() -- Scene where the team returns to the tent after the dungeon run and village scene
		else
			GROUND:Hide('Partners_Bed')
			GAME:FadeIn(20)
		end
	elseif SV.ChapterProgression.Chapter == 2 then 
		GAME:FadeIn(20)
	else
		GAME:FadeIn(20)
	end
end

