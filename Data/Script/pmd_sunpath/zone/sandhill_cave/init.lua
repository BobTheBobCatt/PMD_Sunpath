function sandhill_cave.ExitSegment(zone, result, rescue, segmentID, mapID)
	DEBUG.EnableDbgCoro() --Enable debugging this coroutine
	PrintInfo("=>> ExitSegment_sandhill_cave (Sandhill Cave) result "..tostring(result).." segment "..tostring(segmentID))
	GAME:SetRescueAllowed(false)

	if SV.ChapterProgression.Chapter == 1 then 
		if result ~= RogueEssence.Data.GameProgress.ResultType.Cleared then
			--todo: make zone numbering consistent and perhaps better ordered
			if SV.Chapter1.TeamEnteredSandCave and not SV.Chapter1.TeamCompletedSandCave then --player died solo before clearing
				GAME:EndDungeonRun(result, "sp_test_zone", -1, 8, 0, false, false)
				
				UI:SetSpeaker(GAME:GetPlayerPartyMember(0)) --set player as speaker 
				UI:SetSpeakerEmotion("Pain")
				UI:WaitShowDialogue("Ouch...That didn't feel good...")			
	
				GAME:WaitFrames(20)
				
				GAME:EnterZone("sp_test_zone", -1, 8, 0)		
	
			else --failsafe
				print("error in resulting dusty dune completion")
			end
		else 
		
			if SV.Chapter1.TeamEnteredSandCave and not SV.Chapter1.TeamCompletedSandCave then --player made it through solo
				SV.Chapter1.TeamCompletedSandCave = true	
				GeneralFunctions.EndDungeonRun(result, "sp_test_zone", -1, 9, 0, false, false)		
				
			else--failsafe 
				print("error in resulting dusty dune completion")
			end
		end
	else--generic case (no special cutscenes to be played)
		--This shouldn't be needed, but just in case.
		--Placeholder
		COMMON.ExitDungeonMissionCheck(zone.ID, segmentID)
		
		--set generic flags for generic end of day / start of next day.
		SV.TemporaryFlags.Dinnertime = true 
		SV.TemporaryFlags.Bedtime = true
		SV.TemporaryFlags.MorningWakeup = true 
		SV.TemporaryFlags.MorningAddress = true 
		
		if result == RogueEssence.Data.GameProgress.ResultType.Cleared then	
			GAME:EnterGroundMap('sandhill_cave', 'Main_Entrance_Marker') --Go to Dusty Dune, end dungeon run in the ground rather than here 
		else 
			local exit_ground = 6
			if SV.TemporaryFlags.MissionCompleted then exit_ground = 22 end 
			GeneralFunctions.EndDungeonRun(result, "sp_test_zone", -1, exit_ground, 0, true, true)				
		end
	end
end

return sandhill_cave
