---dusty_dune.ExitSegment(zone, result, rescue, segmentID, mapID)
--Engine callback function
--1 for Dusty Dune, 2 for Abandoned Crossroads
function dusty_dune.ExitSegment(zone, result, rescue, segmentID, mapID)
	DEBUG.EnableDbgCoro() --Enable debugging this coroutine
	PrintInfo("=>> ExitSegment_dusty_dune (Dusty Dune) result "..tostring(result).." segment "..tostring(segmentID))
	GAME:SetRescueAllowed(false)

	if SV.ChapterProgression.Chapter == 1 then 
		if result ~= RogueEssence.Data.GameProgress.ResultType.Cleared then
			--todo: make zone numbering consistent and perhaps better ordered
			if SV.Chapter1.PlayerEnteredDune and not SV.Chapter1.PlayerCompletedDune then --player died solo before clearing
				GAME:EndDungeonRun(result, "sp_test_zone", -1, 1, 0, false, false)
				
				UI:SetSpeaker(GAME:GetPlayerPartyMember(0)) --set player as speaker 
				UI:SetSpeakerEmotion("Pain")
				UI:WaitShowDialogue("Ack... That was rough...")			
	
				GAME:WaitFrames(20)
				
				GAME:EnterZone("sp_test_zone", -1, 1, 0)		-- Send to Dusty Dune ground map

			elseif SV.Chapter1.PartnerEnteredDune and not SV.Chapter1.PartnerCompletedDune then --the partner got wiped before making it to the end
				GAME:EndDungeonRun(result, "sp_test_zone", -1, 1, 0, false, false)
				
				UI:SetSpeaker(GAME:GetPlayerPartyMember(0)) --set partner  as speaker 
				UI:SetSpeakerEmotion("Pain")
				UI:WaitShowDialogue("Ouch... That didn't feel good...")			
				
				GAME:WaitFrames(20)

				GAME:EnterZone("sp_test_zone", -1, 2, 0)				-- Send to Abandoned Crossroads ground map
			else --failsafe
				print("error in resulting dusty dune completion")
			end
		else 
		
			if SV.Chapter1.PlayerEnteredDune and not SV.Chapter1.PlayerCompletedDune then --player made it through solo
				SV.Chapter1.PlayerCompletedDune = true	
				GeneralFunctions.EndDungeonRun(result, "sp_test_zone", -1, 2, 0, false, false)		-- Send to Abandoned Crossroads ground map
				
			elseif SV.Chapter1.PartnerEnteredDune and not SV.Chapter1.PartnerCompletedDune then --the parter made it to the end solo
				SV.Chapter1.PartnerCompletedDune = true
				GeneralFunctions.EndDungeonRun(result, "sp_test_zone", -1, 1, 0, false, false)		-- Send to Dusty Dune ground map
			else--failsafe 
				print("error in resulting dusty dune completion")
			end
		end
	else--generic case (no special cutscenes to be played)
		--This shouldn't be needed, but just in case.
		--Placeholder
		COMMON.ExitDungeonMissionCheck(zone.ID, segmentID)
		
		--set generic flags for generic end of day / start of next day.
		SV.TemporaryFlags.Dinnertime = true 
		SV.TemporaryFlags.Bedtime = true
		SV.TemporaryFlags.MorningWakeup = true 
		SV.TemporaryFlags.MorningAddress = true 
		
		if result == RogueEssence.Data.GameProgress.ResultType.Cleared then	
			GAME:EnterGroundMap('dusty_dune', 'Main_Entrance_Marker') --Go to Dusty Dune, end dungeon run in the ground rather than here 
		else 
			local exit_ground = 6
			if SV.TemporaryFlags.MissionCompleted then exit_ground = 22 end 
			GeneralFunctions.EndDungeonRun(result, "sp_test_zone", -1, exit_ground, 0, true, true)				
		end
	end
end

